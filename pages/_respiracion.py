
# Copilot, desarrolla una página de ejercicios
# de respiración para Stress App.
#
# Función: mostrar_respiracion()
#
# Recibe:
# - La selección del ejercicio por el usuario.
# - La cantidad de ciclos seleccionados.
#
# Devuelve:
# - Instrucciones visuales de respiración.
# - Un mensaje al terminar el ejercicio.
#
# Funcionalidades:
# - Mostrar instrucciones sencillas.
# - Permitir elegir entre ejercicios suaves.
# - Mostrar las fases de inhalar y exhalar.
# - Permitir iniciar y detener el ejercicio.
# - Mostrar el progreso de los ciclos.
#
# Casos borde:
# - El usuario no selecciona un ejercicio.
# - El usuario interrumpe el ejercicio.
# - Se selecciona una cantidad inválida.
# - El usuario reinicia la actividad.
#
# Requisitos:
# - Utilizar Streamlit.
# - No bloquear la aplicación.
# - Permitir detener el ejercicio.
# - Evitar instrucciones de contener el aire.
# - Incluir docstrings en español.
# - Agregar comentarios en español.
